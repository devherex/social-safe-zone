#!/usr/bin/env python3
"""Export zones.json to CSS variables or a TypeScript module (Remotion / web / any JS tool).

  export_zones.py css > templates/safezone.css
  export_zones.py ts  > templates/zones.ts
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import zones_lib as Z

fmt = sys.argv[1] if len(sys.argv) > 1 else "css"
presets = Z.load()["presets"]
if fmt == "css":
    print("/* generated by export_zones.py - do not edit by hand */")
    for name in presets:
        p = Z.preset(name)
        x, y, w, h = Z.safe_rect(p)
        print(f".sz-{name} {{ --sz-w: {p['width']}px; --sz-h: {p['height']}px; "
              f"--sz-top: {y}px; --sz-bottom: {p['safe']['bottom']}px; --sz-left: {x}px; --sz-right: {p['safe']['right']}px; }}")
    print("""
/* usage: <div class="frame sz-ig-reel"><div class="safe">...text, logos...</div></div> */
.frame { position: relative; width: var(--sz-w); height: var(--sz-h); overflow: hidden; }
.frame .safe { position: absolute; top: var(--sz-top); bottom: var(--sz-bottom);
               left: var(--sz-left); right: var(--sz-right); }
/* toggle the guide: add class "debug" to .frame */
.frame.debug .safe { outline: 3px solid #28e678; background: rgba(40,230,120,.06); }""")
else:
    print("// generated by export_zones.py - do not edit by hand")
    print("export const ZONES = {")
    for name in presets:
        p = Z.preset(name)
        print(f"  '{name}': {{ width: {p['width']}, height: {p['height']}, safe: {p['safe']}, avoid: {p.get('avoid', [])} }},")
    print("} as const;\nexport type ZonePreset = keyof typeof ZONES;")
